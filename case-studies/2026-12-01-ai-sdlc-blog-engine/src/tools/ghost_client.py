BLUEPRINT_START_MARKER = "<!-- AI-SDLC-BLUEPRINT-START -->"
BLUEPRINT_END_MARKER = "<!-- AI-SDLC-BLUEPRINT-END -->"
MANIFESTO_URL = "https://blog.marzeta.pl/writing-is-no-longer-proof-of-work-amplifier-of-intent/"
GOEDECKE_URL = "https://www.seangoedecke.com/writing-is-no-longer-proof-of-work/"


def _b64url_encode(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def make_ghost_jwt(api_key: str, now: int | None = None) -> str:
    if ":" not in api_key:
        raise ValueError("GHOST_ADMIN_API_KEY must be in format '<id>:<secret_hex>'")
    key_id, secret_hex = api_key.strip().split(":", 1)
    secret_bytes = bytes.fromhex(secret_hex)
    issued_at = int(time.time()) if now is None else int(now)

    header = {"alg": "HS256", "typ": "JWT", "kid": key_id}
    payload = {"iat": issued_at, "exp": issued_at + 300, "aud": "/admin/"}

    header_b64 = _b64url_encode(json.dumps(header, separators=(",", ":")).encode("utf-8"))
    payload_b64 = _b64url_encode(json.dumps(payload, separators=(",", ":")).encode("utf-8"))
    signing_input = f"{header_b64}.{payload_b64}".encode("ascii")
    signature = hmac.new(secret_bytes, signing_input, hashlib.sha256).digest()
    sig_b64 = _b64url_encode(signature)
    return f"{header_b64}.{payload_b64}.{sig_b64}"


def _format_summary_point(pt: Any) -> str:
    if isinstance(pt, dict):
        return "; ".join(f"{k}: {v}" for k, v in pt.items())
    return str(pt)


def render_blueprint_html(
    metrics: dict[str, Any],
    case_study_url: str,
    summary_points: list[Any] | None = None,
) -> str:
    code_loc = str(metrics.get("code_loc", "N/A"))
    if code_loc.isdigit():
        code_loc = f"{code_loc} LOC implementation"
    test_count = str(metrics.get("test_count", "N/A"))
    if test_count.isdigit():
        test_count = f"{test_count} automated tests & verification checks"
    specs_count = metrics.get("specs_count", "N/A")
    plans_count = metrics.get("plans_count", "N/A")
    models = ", ".join(metrics.get("models_used", ["Gemini 4 Argon (High)"]))

    points_html = ""
    if summary_points:
        items = "".join(f"<li>{html_lib.escape(_format_summary_point(pt))}</li>" for pt in summary_points)
        points_html = f"<ul>{items}</ul>"

    safe_url = html_lib.escape(case_study_url, quote=True)
    return (
        f"{BLUEPRINT_START_MARKER}"
        '<hr><section id="ai-sdlc-blueprint">'
        "<h2>The AI-SDLC Blueprint (How This Was Engineered)</h2>"
        "<p><em>Every project on this blog is built using a deterministic, spec-driven AI Software Development Life Cycle (SDLC) — turning autonomous coding agents into disciplined production engineering pipelines with zero architectural drift.</em></p>"
        "<ul>"
        f"<li><strong>Production Footprint:</strong> {html_lib.escape(code_loc)}</li>"
        f"<li><strong>Verification &amp; Quality Gate:</strong> {html_lib.escape(test_count)}</li>"
        f"<li><strong>Spec-First Governance:</strong> {html_lib.escape(str(specs_count))} design specs &amp; {html_lib.escape(str(plans_count))} step-by-step TDD implementation plans written before code</li>"
        f"<li><strong>Agentic Stack:</strong> {html_lib.escape(models)} orchestrated in AGY</li>"
        "</ul>"
        f"{points_html}"
        f'<p><strong>Proof of Work (Specs, Plans &amp; Source Code):</strong> <a href="{safe_url}">Explore the complete case study repository on GitHub &rarr;</a></p>'
        '<p><strong>Authorship &amp; Proof-of-Work Disclosure (<em>An Amplifier of Intent, Not a Source of Ideas</em>):</strong> '
        'The prose and implementation code on this blog are generated by AI agents operating as hyper-literal contractors with encyclopedic memory and zero agency—while 100% of the problem selection, creative direction, architectural boundaries, and verification gates originate from my mind. '
        f'As Sean Goedecke argues in <a href="{GOEDECKE_URL}"><em>Writing Is No Longer Proof of Work</em></a>, real engineering proof of work is system effectiveness and verifiable outcomes, not hours spent manually wordsmithing sentences. '
        f'<a href="{MANIFESTO_URL}">Read the full AI-SDLC Authorship Manifesto &rarr;</a></p>'
        "</section>"
        f"{BLUEPRINT_END_MARKER}"
    )


def strip_blueprint_html(existing_html: str) -> str:
    pattern_markers = re.compile(
        re.escape(BLUEPRINT_START_MARKER) + r".*?" + re.escape(BLUEPRINT_END_MARKER),
        re.DOTALL,
    )
    cleaned = pattern_markers.sub("", existing_html)
    pattern_section = re.compile(
        r'(?:<hr\s*/?>\s*)?<section[^>]*id=["\']ai-sdlc-blueprint["\'][^>]*>.*?</section>',
        re.DOTALL | re.IGNORECASE,
    )
    cleaned = pattern_section.sub("", cleaned)
    pattern_lexical_h2 = re.compile(
        r'(?:<hr\s*/?>\s*)?<h2[^>]*>\s*The AI-SDLC Blueprint\b.*$',
        re.DOTALL | re.IGNORECASE,
    )
    return pattern_lexical_h2.sub("", cleaned).rstrip()


def inject_blueprint_html(existing_html: str, blueprint_html: str) -> str:
    base = strip_blueprint_html(existing_html)
    return base + "\n" + blueprint_html if base else blueprint_html


class GhostAdminClient:
    def __init__(self, api_key: str, base_url: str = "http://127.0.0.1:2368") -> None:
        self.api_key = api_key
        self.base_url = base_url.rstrip("/")

    def _request(
        self,
        method: str,
        path: str,
        payload: dict[str, Any] | None = None,
        query: dict[str, str] | None = None,
    ) -> dict[str, Any]:
        url = f"{self.base_url}/ghost/api/admin/{path.lstrip('/')}"
        if query:
            url += "?" + urllib.parse.urlencode(query)

        data = None
        if payload is not None:
            data = json.dumps(payload).encode("utf-8")

        token = make_ghost_jwt(self.api_key)
        req = urllib.request.Request(url, data=data, method=method)
        req.add_header("Authorization", f"Ghost {token}")
        req.add_header("X-Forwarded-Proto", "https")
        req.add_header("Accept-Version", "v5.0")
        if data is not None:
            req.add_header("Content-Type", "application/json")

        with urllib.request.urlopen(req, timeout=20) as resp:
            raw = resp.read()
            return json.loads(raw.decode("utf-8")) if raw else {}

    def get_post_by_slug(self, slug: str) -> dict[str, Any] | None:
        try:
            res = self._request("GET", f"posts/slug/{urllib.parse.quote(slug)}/", query={"formats": "html,lexical"})
            posts = res.get("posts", [])
            return posts[0] if posts else None
        except urllib.error.HTTPError as exc:
            if exc.code == 404:
                return None
            raise

    def get_post_by_id(self, post_id: str) -> dict[str, Any]:
        res = self._request("GET", f"posts/{urllib.parse.quote(post_id)}/", query={"formats": "html,lexical"})
        return res["posts"][0]

    def create_post_html(
        self,
        title: str,
        slug: str,
        html: str,
        status: str = "draft",
        tags: list[dict[str, str]] | None = None,
        custom_excerpt: str | None = None,
        featured: bool = False,
        published_at: str | None = None,
    ) -> dict[str, Any]:
        post_data: dict[str, Any] = {
            "title": title,
            "slug": slug,
            "html": html,
            "status": status,
            "featured": bool(featured),
        }
        if tags is not None:
            post_data["tags"] = tags
        if custom_excerpt is not None:
            post_data["custom_excerpt"] = custom_excerpt
        if published_at is not None:
            post_data["published_at"] = published_at

        res = self._request(
            "POST",
            "posts/",
            payload={"posts": [post_data]},
            query={"source": "html"},
        )
        return res["posts"][0]

    def update_post_html(
        self,
        post_id: str,
        html: str,
        tags: list[dict[str, str]] | None = None,
        custom_excerpt: str | None = None,
        title: str | None = None,
        status: str | None = None,
        featured: bool | None = None,
        published_at: str | None = None,
    ) -> dict[str, Any]:
        current = self.get_post_by_id(post_id)
        post_update: dict[str, Any] = {
            "updated_at": current["updated_at"],
            "html": html,
        }
        if tags is not None:
            post_update["tags"] = tags
        if custom_excerpt is not None:
            post_update["custom_excerpt"] = custom_excerpt
        if title is not None:
            post_update["title"] = title
        if status is not None:
            post_update["status"] = status
        if featured is not None:
            post_update["featured"] = bool(featured)
        if published_at is not None:
            post_update["published_at"] = published_at

        res = self._request(
            "PUT",
            f"posts/{urllib.parse.quote(post_id)}/",
            payload={"posts": [post_update]},
            query={"source": "html"},
        )
        return res["posts"][0]

    def get_page_by_slug(self, slug: str) -> dict[str, Any] | None:
        try:
            res = self._request("GET", f"pages/slug/{urllib.parse.quote(slug)}/", query={"formats": "html,lexical"})
            pages = res.get("pages", [])
            return pages[0] if pages else None
        except urllib.error.HTTPError as exc:
            if exc.code == 404:
                return None
            raise

    def update_page_html(
        self,
        slug: str,
        title: str,
        html: str,
        status: str = "published",
    ) -> dict[str, Any]:
        current = self.get_page_by_slug(slug)
        if current is None:
            res = self._request(
                "POST",
                "pages/",
                payload={"pages": [{"slug": slug, "title": title, "html": html, "status": status}]},
                query={"source": "html"},
            )
            return res["pages"][0]

        page_id = current["id"]
        res = self._request(
            "PUT",
            f"pages/{urllib.parse.quote(page_id)}/",
            payload={
                "pages": [
                    {
                        "updated_at": current["updated_at"],
                        "title": title,
                        "html": html,
                        "status": status,
                    }
                ]
            },
            query={"source": "html"},
        )
        return res["pages"][0]

    def ensure_tags(self, tags: list[dict[str, str]]) -> list[dict[str, Any]]:
        existing_res = self._request("GET", "tags/", query={"limit": "all"})
        by_slug = {t["slug"]: t for t in existing_res.get("tags", [])}
        ensured = []
        for tag in tags:
            slug = tag["slug"]
            if slug in by_slug:
                ensured.append(by_slug[slug])
            else:
                created = self._request("POST", "tags/", payload={"tags": [tag]})
                ensured.append(created["tags"][0])
        return ensured
